function addDaysIstIso(baseIso: string, deltaDays: number, istHour = 14, istMinute = 15): string {
  const base = new Date(baseIso);
  // Shift base to target day and set clean UTC timestamp corresponding to IST hour/min (IST = UTC+05:30)
  const dt = new Date(Date.UTC(base.getUTCFullYear(), base.getUTCMonth(), base.getUTCDate() + deltaDays));
  const totalMinutesUtc = istHour * 60 + istMinute - 330; // subtract 5h30m
  dt.setUTCMinutes(totalMinutesUtc);
  return dt.toISOString();
}

function nextFirstOfMonth(dateKey: string): string {
  const [y, m] = dateKey.split('-').map(Number);
  const nextMonth = (m || 1) === 12 ? 1 : (m || 1) + 1;
  const nextYear = (m || 1) === 12 ? (y || 2026) + 1 : (y || 2026);
  return `${nextYear}-${String(nextMonth).padStart(2, '0')}-01`;
}

function firstOfCurrentMonth(dateKey: string): string {
  return `${dateKey.slice(0, 7)}-01`;
}

